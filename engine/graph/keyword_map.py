def match_subject(text: str) -> list[tuple[str, str, int]]:
    """
    对题材文本进行多赛道匹配，返回 [(L1, L2, score), ...] 按 score 降序。
    score = 命中关键词数量。
    """
    text_lower = text.lower()
    results = []
    for l1, l2_dict in AI_KEYWORD_MAP.items():
        for l2, kws in l2_dict.items():
            score = sum(1 for kw in kws if kw.lower() in text_lower)
            if score > 0:
                results.append((l1, l2, score))
    results.sort(key=lambda x: -x[2])
    return results
